# sparks: (frame, x, y, color) in cell coords; each rises over three frames, hot then cooling
SPARKS = [
    (1, 11, 8, "y"), (2, 12, 5, "y"), (3, 12, 2, "x"),
    (4, 3, 8, "y"), (5, 2, 5, "y"), (0, 2, 2, "x"),
]

# coal clusters on the bowl's interior row, pulsing out of phase
COALS = {
    0: [(3, "x"), (4, "y"), (12, "w"), (11, "x")],
    1: [(3, "x"), (4, "y"), (12, "x"), (11, "y")],
    2: [(3, "w"), (4, "x"), (12, "x"), (11, "y")],
    3: [(3, "w"), (4, "x"), (12, "w"), (11, "x")],
    4: [(3, "x"), (4, "x"), (12, "w"), (11, "x")],
    5: [(3, "x"), (4, "y"), (12, "w"), (11, "w")],
}


def base(lit):
    """Draw the base on the native Cinder pixel grid."""
    c = Canvas(W, H)
    c.stamp(PEDESTAL, 0, 21)
    c.stamp(BOWL, 1, 15)
    if not lit:
        # one cold ash mound heaped in the bowl, rising just above the rim
        c.stamp("""
            ...ee...
            ..deeed.
            .cdddddc
            cccddccc
        """, 3, 13)
    c.outline("K")
    return c


def brazier_frame(t, lit=True):
    """Draw the brazier frame on the native Cinder pixel grid."""
    c = base(lit)
    if not lit:
        return c
    for x, ch in COALS[t]:
        c.set(x, 16, ch)
    rows = FLAME[t].strip("\n").split("\n")
    rows = [r.strip() for r in rows]
    for j, r in enumerate(rows):
        for i, ch in enumerate(r):
            if ch != ".":
                c.set(3 + i, 2 + j, ch)
    for f, x, y, ch in SPARKS:
        if f == t:
            c.set(x, y, ch)
    return c


def build():
    """Build the sheet with its original cells, anchors and animation contracts."""
    sb = SheetBuilder("cinder_brazier", (W, H), ANCHOR)
    sb.add("brazier_lit", [brazier_frame(t).rgba() for t in range(6)], durations=[6, 6, 5, 5, 6, 6], footprint=[10, 5],
           light={"color": "#efb68a", "radius": 64, "intensity": 0.9, "offset": [0, -20]})
    sb.add("brazier_unlit", [brazier_frame(0, lit=False).rgba()], footprint=[10, 5])
    return sb


