def grid_canvas(s):
    """Draw the grid canvas on the native Cinder pixel grid."""
    rows = s.strip("\n").split("\n")
    c = Canvas(W, H)
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch != ".":
                c.set(x, y, ch)
    return c


def urn_broken():
    """The tall urn's lower half after a hit: jagged far rim (lit fracture), dark interior, a lower near rim,
    and two shards on the ground beside it."""
    c = grid_canvas(URN_TALL)
    far = {2: 10, 3: 9, 4: 8, 5: 9, 6: 9, 7: 10, 8: 9, 9: 8, 10: 9, 11: 9, 12: 10, 13: 10}
    for x in range(W):
        for y in range(far.get(x, 16)):
            c.set(x, y, ".")
    for x, top in far.items():
        if c.get(x, top) in ".K":
            continue
        c.set(x, top, "E" if x < 8 else "D")
        if 4 <= x <= 11:
            near = 11 if x in (4, 11) else 12
            for y in range(top + 1, near):
                c.set(x, y, "1" if 5 <= x <= 10 else "A")
            c.set(x, near, "D" if x < 8 else "C")
    c.a[c.a == "K"] = "."
    c.stamp("""
        .DC
        DCB
    """, 0, 12)
    c.stamp("""
        ED.
        CBA
    """, 13, 12)
    c.outline("K")
    return c


def lava_frames(src, hot_map):
    """Pulse: swap each glowing color one step hotter for the middle frames."""
    base = grid_canvas(src)
    frames = []
    for step in (0, 1, 1, 0):
        c = base.copy()
        if step:
            for y in range(H):
                for x in range(W):
                    ch = c.a[y, x]
                    if ch in hot_map:
                        c.a[y, x] = hot_map[ch]
        frames.append(c)
    return frames


HOTTER = {"x": "y"}


NOTES = "Small relics use cold mineral stone; the lava rock alone is hot."


def build():
    """Build the sheet with its original cells, anchors and animation contracts."""
    sb = SheetBuilder("cinder_props", (W, H), ANCHOR)
    sb.notes = NOTES
    sb.add("urn_tall", [grid_canvas(URN_TALL).rgba()], footprint=[9, 4], breakable=True)
    sb.add("urn_squat", [grid_canvas(URN_SQUAT).rgba()], footprint=[11, 4], breakable=True)
    sb.add("urn_broken", [urn_broken().rgba()])
    lit = {"color": "#efb68a", "radius": 22, "intensity": 0.6, "offset": [0, -3]}
    sb.add("lava_rock", [f.rgba() for f in lava_frames(LAVA_ROCK_A, HOTTER)], durations=[18, 12, 18, 12],
           footprint=[10, 4], light=lit)
    sb.add("skull", [grid_canvas(SKULL).rgba()])
    sb.add("bones", [grid_canvas(BONES).rgba()])
    sb.add("ribs", [grid_canvas(RIBS).rgba()])
    sb.add("shard_small", [grid_canvas(SHARD_SMALL).rgba()], footprint=[8, 3])
    sb.add("pebbles", [grid_canvas(PEBBLES).rgba()])
    sb.add("ash_pile", [grid_canvas(ASH_PILE).rgba()])
    return sb


