def grid_canvas(s):
    """Draw the grid canvas on the native Cinder pixel grid."""
    rows = s.strip("\n").split("\n")
    c = Canvas(T, T)
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch != ".":
                c.set(x, y, ch)
    c.replace("1", "a")  # Pebble occlusion shares the crack soot instead of a one-pixel near-duplicate.
    return c


def build():
    """Build the sheet with its original cells, anchors and animation contracts."""
    sb = SheetBuilder("cinder_tiles", (T, T), [8, 8])
    sb.notes = ("Row 0: three ash ground fills (base #363340) that tile seamlessly in any mix. Other rows are "
                "transparent decals for the code-painted ground: no outlines, place them anywhere on ash. "
                "Lava banks and cliffs are painted in code by the region builder, so there are no bank tiles. Multi-frame rows are variants to pick from, not animations.")
    sb.add("ground_ash", [fill(s, n).rgba() for s, n in ((1, 1), (7, 2), (12, 1))], fps=1)
    sb.add("crack", [crack(3, 11).rgba(), crack(9, 9).rgba(), crack(21, 7, branch=False).rgba()], fps=1)
    sb.add("ash_drift", [grid_canvas(DRIFT_A).rgba(), grid_canvas(DRIFT_B).rgba()], fps=1)
    sb.add("scorch", [grid_canvas(SCORCH).rgba()])
    sb.add("bone_bits", [grid_canvas(BONE_BITS).rgba()])
    sb.add("pebbles", [grid_canvas(PEBBLES).rgba()])
    return sb


