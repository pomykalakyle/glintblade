"""cinder_tiles (16x16): three seamless ash ground fills, then transparent decals the region builder can scatter
over its code-painted ground (cracks, ash drifts, a scorch mark, bone bits, pebbles, a basalt crack).

Decals have no black outline: a crack is a dark line with a 1 px lit lip below it (light from the upper left),
a drift is a pale mound whose lower-right rim is a shade darker than the ground. Fills keep their texture
clusters away from the tile edges so any arrangement tiles without seams.
"""

import random

from draw import Canvas
from lib import SheetBuilder

T = 16


def fill(seed, n):
    """Ash ground: flat base with a few 2-3 px clusters (pale ash flecks and darker pits), none on the edge."""
    rng = random.Random(seed)
    c = Canvas(T, T)
    c.a[:] = "c"
    shapes = [
        ["d.", "dd"], ["dd"], [".e", "dd"],      # pale flecks, lit on the upper left
        ["b"], ["bb"], ["b.", ".b"],             # small pits
    ]
    placed = []
    for _ in range(200):
        if len(placed) >= n:
            break
        sh = rng.choice(shapes)
        h, w = len(sh), len(sh[0])
        x, y = rng.randint(2, T - 3 - w), rng.randint(2, T - 3 - h)
        if any(abs(x - px) < 4 and abs(y - py) < 4 for px, py in placed):
            continue
        placed.append((x, y))
        c.stamp(sh, x, y)
    return c


def crack(seed, length, branch=True):
    """A wandering dark crack (a, softening to b at the tips) with a lit lip under its flatter segments."""
    rng = random.Random(seed)
    c = Canvas(T, T)
    x, y = 3, rng.randint(4, 6)
    pts = [(x, y)]
    for i in range(length):
        x += 1
        if rng.random() < 0.45:
            y += rng.choice((-1, 1, 1))
        y = max(2, min(T - 3, y))
        if x > T - 3:
            break
        pts.append((x, y))
    for i, (px, py) in enumerate(pts):
        tip = i < 1 or i >= len(pts) - 2
        c.set(px, py, "b" if tip else "a")
    for i, (px, py) in enumerate(pts[1:-1], 1):
        if pts[i - 1][1] == py and c.get(px, py + 1) == ".":
            c.set(px, py + 1, "d")
    if branch and len(pts) > 6:
        bx, by = pts[len(pts) // 2]
        for k in range(1, 4):
            if c.get(bx + k // 2, by + k) == ".":
                c.set(bx + k // 2, by + k, "a" if k < 3 else "b")
        c.set(bx + 1, by + 2, "d") if c.get(bx + 1, by + 2) == "." else None
    return c


