def bright(cv, n=1):
    """Raise source-bound heat by one or more discrete palette steps."""
    for _ in range(n):
        cv.remap(BRIGHT)
    return cv


def canvas():
    """Create an empty cell at the original sprite dimensions."""
    return pix.Canvas(CW, CH)


def frame(g, dx=0, dy=0):
    """Place a hand-authored side pose at its original anchor."""
    cv = canvas()
    cv.stamp(g, GX + dx, GY + dy)
    return cv


def cut(g, x0, y0, x1, y1):
    """Extract an exact pixel rectangle from an authored grid."""
    g = pix.grid(g)
    return [row[x0:x1] for row in g[y0:y1]]


