def head_dip(text, col=19):
    """Lower only the head columns by one row while the chest, ridge and paws stay planted."""
    g = pix.grid(text)
    out = [list(r) for r in g]
    for x in range(col, len(g[0])):
        for y in range(len(g) - 1, 0, -1):
            out[y][x] = g[y - 1][x]
        out[0][x] = "."
    return "\n".join("".join(r) for r in out)


def tail_flick(text):
    """Lift the hanging tail tip one row so the idle has a small secondary motion."""
    g = [list(r) for r in pix.grid(text)]
    g[8][0], g[9][0], g[10][0] = "c", "R", "."
    return "\n".join("".join(r) for r in g)


