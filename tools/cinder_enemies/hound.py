def vertical(text, at):
    """Stamp one authored vertical pose into the unchanged cell."""
    return canvas().stamp(text, *at)


def vertical_anims(look):
    """Animate compressed, extended and settled vertical key poses without sliding feet."""
    down = look == "down"
    at = (12, 1) if down else (14, 2)
    standing = vertical(DOWN if down else UP, at)
    loaded = vertical(DOWN_LOAD if down else UP_LOAD, at)
    flight = vertical(DOWN_FLY if down else UP_FLY, at)
    # Paw lifts occupy only the distal limb, preserving shoulder/haunch mass.
    left = standing.copy()
    right = standing.copy()
    for cv, col in ((left, 4 if down else 1), (right, 9 if down else 10)):
        for x in range(at[0] + col, at[0] + col + 2):
            y = 20 if down else 19  # the paw row in cell coordinates
            cv.set(x, y - 1, cv.get(x, y))
            cv.set(x, y, ".")
    return [standing, bright(standing.copy()), standing.copy(), standing.copy()], \
        [left, standing.copy(), right, standing.copy()], \
        [loaded.copy(), bright(loaded.copy()), bright(loaded.copy(), 2), bright(loaded.copy(), 2)], \
        [bright(loaded.copy()), bright(flight.copy()), bright(flight.shift(0, 1)), loaded.copy()], \
        [bright(loaded.copy(), 2), standing.copy()]


DUR = {"idle": [14, 10, 14, 10], "move": [6, 6, 6, 6], "windup": [4, 6, 6, 6],
       "attack": [3, 4, 4, 6], "hurt": [6, 10]}


def all_anims():
    """Return all original animation rows with their original durations and anchors."""
    out = []
    for an, fn in ANIMS.items():
        frames, meta = fn()
        out.append((an + "_right", frames, meta))
    for suffix in ("down", "up"):
        for an, frames in zip(DUR, vertical_anims(suffix)):
            out.append((f"{an}_{suffix}", frames, {"durations": DUR[an]}))
    return out
