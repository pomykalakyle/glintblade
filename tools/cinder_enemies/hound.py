def posed(upper, bob, tail, legs4, dx=0):
    """legs4 = [far hind, near hind, far front, near front], each (joints, paw dir), in torso
    coords. Far legs go behind the body, near legs in front."""
    cv = canvas()
    ox, oy = GX + dx, GY + 7 + bob  # torso origin in cell coords
    for j, p in (legs4[0], legs4[2]):
        leg(cv, [(ox + a, oy + b) for a, b in j], near=False, paw=p)
    cv.stamp(upper, GX + dx, GY + 1 + bob)
    for (tx, ty, ch) in tail:
        cv.set(ox + tx, oy + ty, ch)
    for j, p in (legs4[1], legs4[3]):
        leg(cv, [(ox + a, oy + b) for a, b in j], near=True, paw=p)
    return cv


