def _kern_pairs(pairs):
    """Expand cap pairs to every case mix, since region names are title-cased at runtime."""
    out = {}
    for a, b, v in pairs:
        for x in sorted({a, a.lower()}):
            for y in sorted({b, b.lower()}):
                out[x + y] = v
    return out


# Only pairs whose closest approach stays 4+ px (one more than TRACKING) on every shared row in a
# rendered title: "lo" (Bloomwild, Hollow), "Ci" (Cinder), "'s" (Warden's), "at" (Glasswater).
# "at" stops at -1: at -2 the banner's ink outline fuses the T bar into the A.
KERN = _kern_pairs([("L", "O", -1), ("C", "I", -1), ("'", "S", -1), ("A", "T", -1)])
