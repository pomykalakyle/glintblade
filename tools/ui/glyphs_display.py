# Style v2 (2026-10-30): letters and digits are the narrow cut-stone capitals from cutstone.py,
# the same construction as the logo. The Roman CAPS/DIGITS above are kept only for reference.
from cutstone import letter


def _rows(m):
    """A cut-stone mask as '#'/'.' rows."""
    return ["".join("#" if v else "." for v in r) for r in m]


